from pathlib import Path
import hashlib,shutil,zipfile,json
root=Path('/data/arkham'); dest=Path('/data/ARKHAM-delivery'); dest.mkdir(exist_ok=True)
# Only explicitly selected, inspected previews enter the deliverable.
previews=['collection-desktop','collection-360','collection-grid-desktop','collection-grid-360','filters-desktop','filters-360','category-desktop','category-mobile','product-desktop','product-mobile','product-body-desktop','product-body-mobile','product-zoom','journal-desktop','journal-grid-desktop','journal-grid-mobile','article-desktop','article-mobile','story-desktop','story-chapters','story-mobile','faq-desktop','faq-open-mobile','shipping-desktop','privacy-desktop','terms-desktop','contact-desktop','contact-mobile','contact-form-mobile','cart-desktop','cart-mobile','login-desktop','login-mobile','footer-desktop','footer-mobile','empty-mobile','fallback-mobile','reduced-mobile','home-scene-1','home-scene-4','home-scene-7','home-mobile-390-1','home-mobile-390-3','home-collection','home-categories','home-journal','home-faq','skeleton-mobile','mobile-menu']
(root/'qa/previews').mkdir(exist_ok=True)
for old in (root/'qa/previews').glob('*.png'): old.unlink()
for name in previews:
 src=root/'qa/v5'/(name+'.png')
 if src.exists(): shutil.copy2(src,root/'qa/previews'/src.name)
allowed_root=['README.fa.md','.env.example','.gitignore','.dockerignore','docker-compose.yml']
files=[root/f for f in allowed_root]
for folder in ['backend','frontend','deploy','docs','scripts','qa']:
 for f in (root/folder).rglob('*'):
  if not f.is_file():continue
  rel=f.relative_to(root)
  if str(rel).endswith('-package.json'):continue
  if any(part in ['node_modules','__pycache__','media','staticfiles'] for part in rel.parts):continue
  if str(rel).startswith('frontend/public/docs/'):continue # Regenerated by the build, license is present in dist/docs.
  if folder=='qa' and f.suffix=='.png' and f.parent!=root/'qa/previews':continue
  if f.suffix in ['.log','.pyc','.sock','.pid','.sqlite3']:continue
  files.append(f)
files=sorted(set(files))
manifest='\n'.join(hashlib.sha256(f.read_bytes()).hexdigest()+'  '+str(f.relative_to(root)) for f in files)+'\n'
(root/'MANIFEST.sha256').write_text(manifest)
files.append(root/'MANIFEST.sha256')
archive=dest/'ARKHAM-atelier-v5-source-and-reports.zip'
with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED,compresslevel=9) as z:
 for f in files:z.write(f,Path('arkham')/f.relative_to(root))
secrets=[(root/name).read_bytes().strip() for name in ['.local-secret','.demo-secret'] if (root/name).exists()]
with zipfile.ZipFile(archive) as z:
 assert z.testzip() is None
 names=z.namelist()
 assert not any('/.env' in n and not n.endswith('.env.example') for n in names)
 assert not any('/node_modules/' in n or '/.venv/' in n or '/.pgdata' in n for n in names)
 assert not any(secret in z.read(n) for secret in secrets for n in names)
 for required in ['backend/manage.py','frontend/package-lock.json','frontend/dist/index.html','frontend/src/assets/brand-fallback.webp','deploy/init-db.sh','docs/STATUS.fa.md','qa/reports/v4-backend-and-browser-tests.txt','qa/reports/v4-experience.json','docs/ATELIER-V5.fa.md','qa/reports/v5-preservation.json','qa/reports/v5-polish.json','frontend/src/motion/Motion.tsx','docs/CINEMATIC-ACCEPTANCE.fa.md','frontend/src/experience/ExperienceShell.tsx','backend/demo_assets/thyme.webp','scripts/run-demo.sh','scripts/create-demo-admin.sh']:
  assert 'arkham/'+required in names,required
print(json.dumps({'file_count':len(files),'archive_bytes':archive.stat().st_size,'archive_sha256':hashlib.sha256(archive.read_bytes()).hexdigest(),'secret_scan':'passed','archive_integrity':'passed'}))
